/**
 * Turns the Desk365 OpenAPI 3.0 document into a list of MCP tool definitions.
 *
 * Each operation becomes one tool:
 *   - query/path/header parameters become top-level tool arguments
 *   - a JSON request body becomes a `body` argument
 *   - a multipart (attachment) request body becomes a `file_paths` argument
 */
import { readFileSync } from 'node:fs';

type JsonSchema = Record<string, any>;

export interface ParamDef {
    name: string;
    in: 'query' | 'path' | 'header';
    /** True when the spec says the value is a JSON string (e.g. `ticket_object`, `filters`). */
    jsonString: boolean;
}

export interface ToolDef {
    name: string;
    title: string;
    description: string;
    method: 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE';
    path: string;
    tag: string;
    params: ParamDef[];
    body: 'none' | 'json' | 'multipart';
    inputSchema: JsonSchema;
}

/** JSON Schema keywords we keep; everything else (OpenAPI-only or Springdoc noise) is dropped. */
const KEEP_KEYWORDS = new Set([
    'type',
    'properties',
    'items',
    'required',
    'enum',
    'description',
    'default',
    'additionalProperties',
    'title',
    'minimum',
    'maximum',
    'minLength',
    'maxLength',
    'pattern',
    'minItems',
    'maxItems'
]);

/** Converts the HTML used throughout the Desk365 spec into compact plain text. */
export function htmlToText(html: string | undefined): string {
    if (!html) return '';
    return html
        .replace(/<br\s*\/?>/gi, '\n')
        .replace(/<li[^>]*>/gi, '\n- ')
        .replace(/<\/(p|div|h\d|pre|ul|ol)>/gi, '\n')
        .replace(/<[^>]+>/g, '')
        .replace(/&lt;/g, '<')
        .replace(/&gt;/g, '>')
        .replace(/&quot;/g, '"')
        .replace(/&#39;/g, "'")
        .replace(/&nbsp;/g, ' ')
        .replace(/&amp;/g, '&')
        .replace(/[ \t]+\n/g, '\n')
        .replace(/\n{3,}/g, '\n\n')
        .trim();
}

function resolveRef(spec: any, ref: string): any {
    if (!ref.startsWith('#/')) throw new Error(`Unsupported $ref: ${ref}`);
    return ref
        .slice(2)
        .split('/')
        .reduce((node, key) => node?.[key.replace(/~1/g, '/').replace(/~0/g, '~')], spec);
}

/**
 * Inlines $refs and normalises an OpenAPI schema into plain, permissive JSON Schema.
 * The Desk365 spec is generated by Springdoc and contains quirks (arrays with `properties`,
 * string arrays declared as `items: {type: object}`), so we loosen rather than reject.
 */
function sanitize(spec: any, schema: any, seen: Set<string> = new Set()): JsonSchema {
    if (!schema || typeof schema !== 'object') return {};
    if (schema.$ref) {
        if (seen.has(schema.$ref)) return { type: 'object' }; // recursion guard
        const next = new Set(seen).add(schema.$ref);
        return sanitize(spec, resolveRef(spec, schema.$ref), next);
    }
    for (const combo of ['allOf', 'oneOf', 'anyOf'] as const) {
        if (Array.isArray(schema[combo])) {
            return { [combo]: schema[combo].map((s: any) => sanitize(spec, s, seen)) };
        }
    }

    const out: JsonSchema = {};
    for (const [key, value] of Object.entries(schema)) {
        if (!KEEP_KEYWORDS.has(key)) continue;
        if (key === 'properties') {
            if (schema.type === 'array') continue; // Springdoc noise
            out.properties = Object.fromEntries(
                Object.entries(value as Record<string, any>).map(([k, v]) => [k, sanitize(spec, v, seen)])
            );
        } else if (key === 'items') {
            const items = sanitize(spec, value, seen);
            // `items: {type: object}` paired with string examples (e.g. watcher emails) → accept anything.
            const example = (value as any)?.example ?? schema.example;
            if (items.type === 'object' && !items.properties && Array.isArray(example) && typeof example[0] !== 'object') {
                delete items.type;
            }
            out.items = items;
        } else if (key === 'additionalProperties' && typeof value === 'object') {
            out.additionalProperties = sanitize(spec, value, seen);
        } else if (key === 'description') {
            out.description = htmlToText(value as string);
        } else if (key === 'required') {
            if (Array.isArray(value) && value.length > 0) out.required = value;
        } else {
            out[key] = value;
        }
    }

    // Surface the spec's example in the description: it is often the best documentation available.
    if (schema.example !== undefined && typeof schema.example !== 'object') {
        out.description = [out.description, `Example: ${JSON.stringify(schema.example)}`].filter(Boolean).join(' ');
    }
    if (schema.nullable && typeof out.type === 'string') out.type = [out.type, 'null'];
    if (out.type === 'object' && !out.properties && out.additionalProperties === undefined) {
        out.additionalProperties = true;
    }
    return out;
}

/** Desk365 expects most query values as strings ("0"/"1", "30"), but models often send numbers/booleans. */
function loosenScalar(schema: JsonSchema): JsonSchema {
    if (schema.type === 'string' && !schema.enum) return { ...schema, type: ['string', 'number', 'boolean'] };
    if (schema.type === 'string' && schema.enum) return { ...schema, type: ['string', 'number'], enum: [...schema.enum, ...schema.enum.map(Number).filter((n: number) => !Number.isNaN(n))] };
    if (schema.type === 'integer' || schema.type === 'number') return { ...schema, type: [schema.type, 'string'] };
    if (schema.type === 'boolean') return { ...schema, type: ['boolean', 'string', 'number'] };
    return schema;
}

/** `/v3/asset_mgmt/assets/associate-tickets` + POST → `asset_mgmt_assets_associate_tickets` */
function toolName(method: string, path: string, summary: string): string {
    let name = path
        .replace(/^\/v\d+\//, '')
        .replace(/\/+$/, '')
        .replace(/[{}]/g, '')
        .replace(/[^a-zA-Z0-9]+/g, '_')
        .toLowerCase();
    if (method === 'get' && /^list\b/i.test(summary) && !name.endsWith('_list')) name += '_list';
    return name;
}

const MAX_DESCRIPTION = 3000;

export function loadSpec(specPath: string): any {
    return JSON.parse(readFileSync(specPath, 'utf8'));
}

export function buildTools(spec: any): ToolDef[] {
    const tools: ToolDef[] = [];
    const usedNames = new Set<string>();

    for (const [path, pathItem] of Object.entries<any>(spec.paths ?? {})) {
        const sharedParams = pathItem.parameters ?? [];
        for (const method of ['get', 'post', 'put', 'patch', 'delete'] as const) {
            const op = pathItem[method];
            if (!op) continue;

            const summary: string = op.summary ?? (op.operationId === 'checkStatus' ? 'Check API status (ping)' : op.operationId);
            let name = toolName(method, path, summary);
            while (usedNames.has(name)) name += `_${method}`;
            usedNames.add(name);

            const properties: Record<string, JsonSchema> = {};
            const required: string[] = [];
            const params: ParamDef[] = [];

            for (const rawParam of [...sharedParams, ...(op.parameters ?? [])]) {
                const p = rawParam.$ref ? resolveRef(spec, rawParam.$ref) : rawParam;
                if (!['query', 'path', 'header'].includes(p.in)) continue;
                if (p.in === 'header' && p.name.toLowerCase() === 'authorization') continue;

                const description = htmlToText(p.description);
                // Parameters whose description shows a sample JSON object are JSON-encoded strings.
                const jsonString = /^sample\b[^:]*:/i.test(description) || /_object$/.test(p.name);
                let schema = sanitize(spec, p.schema ?? { type: 'string' });
                if (jsonString) {
                    schema = {
                        type: ['object', 'string'],
                        additionalProperties: true,
                        description: `${description}\n(Pass a JSON object; it will be JSON-encoded for you.)`
                    };
                } else {
                    schema = loosenScalar(schema);
                    if (description) schema.description = description;
                }
                properties[p.name] = schema;
                if (p.required) required.push(p.name);
                params.push({ name: p.name, in: p.in, jsonString });
            }

            let body: ToolDef['body'] = 'none';
            const content = op.requestBody?.content ?? {};
            if (content['application/json']) {
                body = 'json';
                const schema = sanitize(spec, content['application/json'].schema);
                schema.description = [htmlToText(op.requestBody.description), schema.description].filter(Boolean).join('\n');
                properties.body = schema;
                if (op.requestBody.required) required.push('body');
            } else if (content['multipart/form-data']) {
                body = 'multipart';
                properties.file_paths = {
                    type: 'array',
                    items: { type: 'string' },
                    minItems: 1,
                    description: 'Absolute paths of local files (on the machine running this MCP server) to attach.'
                };
                required.push('file_paths');
            }

            let description = [summary, htmlToText(op.description)].filter(Boolean).join('\n\n');
            if (description.length > MAX_DESCRIPTION) description = description.slice(0, MAX_DESCRIPTION) + '…';

            const inputSchema: JsonSchema = { type: 'object', properties, additionalProperties: false };
            if (required.length) inputSchema.required = required;

            tools.push({
                name,
                title: summary,
                description,
                method: method.toUpperCase() as ToolDef['method'],
                path,
                tag: (op.tags?.[0] ?? 'misc').replace(/^\d+\.\s*/, ''),
                params,
                body,
                inputSchema
            });
        }
    }
    return tools.sort((a, b) => a.name.localeCompare(b.name));
}
